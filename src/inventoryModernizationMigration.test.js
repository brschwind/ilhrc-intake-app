test("bundle assembly is atomic and splitting returns components to Processing", async () => {
  const db = await database();
  await db.exec(`
    insert into public.items (id, sku, title, item_type) values
      ('one','SKU-ONE','Part One','individual'),
      ('two','SKU-TWO','Part Two','individual'),
      ('bundle','SKU-BUNDLE','Complete Set','bundle');
    insert into public.bundle_components (bundle_item_id, component_item_id, piece_quantity)
    values ('bundle','one',1), ('bundle','two',1);
    insert into public.inventory_locations (code, display_name, location_type, last_verified_at)
    values ('B1','B1','shelf',now());
    insert into public.inventory_by_location (item_id, location_id, quantity)
    select 'one', id, 1 from public.inventory_locations where code='B1';
  `);
  await assert.rejects(
    db.query("select public.assemble_inventory_bundle('bundle')"),
    /component no longer has enough/i
  );
  assert.equal(Number(await scalar(db, "select quantity from public.items where id='one'")), 1);
  assert.equal(Number(await scalar(db, "select quantity from public.items where id='bundle'")), 0);

  await db.exec(`
    insert into public.inventory_by_location (item_id, location_id, quantity)
    select 'two', id, 1 from public.inventory_locations where code='B1';
  `);
  await db.query("select public.assemble_inventory_bundle('bundle')");
  assert.equal(Number(await scalar(db, "select quantity from public.items where id='one'")), 0);
  assert.equal(Number(await scalar(db, "select quantity from public.items where id='two'")), 0);
  assert.equal(Number(await scalar(db, "select quantity from public.inventory_location_details where item_id='bundle' and code='PROCESSING'")), 1);

  await db.query("select public.split_inventory_bundle('bundle')");
  assert.equal(Number(await scalar(db, "select quantity from public.items where id='bundle'")), 0);
  assert.equal(await scalar(db, "select status from public.items where id='bundle'"), "Removed");
  assert.equal(Number(await scalar(db, "select quantity from public.inventory_location_details where item_id='one' and code='PROCESSING'")), 1);
  assert.equal(Number(await scalar(db, "select quantity from public.inventory_location_details where item_id='two' and code='PROCESSING'")), 1);
  await db.close();
});

test("ISBN consolidation moves every location quantity to the surviving record", async () => {
  const db = await database();
  await db.exec(`
    insert into public.items (id, sku, title, isbn) values
      ('keeper','SKU-KEEP','Keeper','9781234567897'),
      ('duplicate','SKU-DUP','Duplicate','9781234567897');
    insert into public.inventory_locations (code, display_name, location_type, last_verified_at)
    values ('C1','C1','shelf',now()), ('C2','C2','shelf',now());
    insert into public.inventory_by_location (item_id, location_id, quantity)
    select 'keeper', id, 1 from public.inventory_locations where code='C1';
    insert into public.inventory_by_location (item_id, location_id, quantity)
    select 'duplicate', id, case code when 'C1' then 2 else 3 end
    from public.inventory_locations where code in ('C1','C2');
  `);
  await db.query(`select public.merge_inventory_items(
    'keeper', array['duplicate'],
    '{"title":"Keeper","final_price":"5.00","publisher":"","curriculum":"","subject":"","grade_level":"","category":"","edition":""}'::jsonb
  )`);
  assert.equal(Number(await scalar(db, "select quantity from public.items where id='keeper'")), 6);
  assert.equal(Number(await scalar(db, "select quantity from public.inventory_location_details where item_id='keeper' and code='C1'")), 3);
  assert.equal(Number(await scalar(db, "select quantity from public.inventory_location_details where item_id='keeper' and code='C2'")), 3);
  assert.equal(Number(await scalar(db, "select count(*) from public.items where id='duplicate'")), 0);
  assert.equal(Number(await scalar(db, "select count(*) from public.inventory_by_location where item_id='duplicate'")), 0);
  await db.close();
});

test("bulk removal archives location quantities without deleting catalog history", async () => {
  const db = await database();
  await db.exec(`
    insert into public.items (id, sku, title) values
      ('remove-one','SKU-R1','Remove One'), ('remove-two','SKU-R2','Remove Two');
    insert into public.inventory_by_location (item_id, location_id, quantity)
    select item_id, location.id, 2
    from (values ('remove-one'), ('remove-two')) selected(item_id)
    cross join public.inventory_locations location where location.code='PROCESSING';
  `);
  const result = await db.query("select public.archive_inventory_items(array['remove-one','remove-two'],'test removal') as count");
  assert.equal(Number(result.rows[0].count), 2);
  assert.equal(Number(await scalar(db, "select sum(quantity) from public.inventory_by_location where item_id in ('remove-one','remove-two')")), 0);
  assert.equal(Number(await scalar(db, "select count(*) from public.items where id in ('remove-one','remove-two') and status='Removed'")), 2);
  assert.equal(Number(await scalar(db, "select count(*) from public.inventory_events where item_id in ('remove-one','remove-two') and action_type='removal'")), 2);
  await db.close();
});

