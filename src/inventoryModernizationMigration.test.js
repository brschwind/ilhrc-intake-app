async function database({ migrated = true } = {}) {
  const db = new PGlite();
  await db.exec(`
    create role authenticated; create role anon; create role service_role;
    create schema auth;
    create table auth.users (id uuid primary key default gen_random_uuid());
    create function auth.uid() returns uuid language sql stable as $$ select null::uuid $$;
    create table public.items (
      id text primary key, sku text unique, title text not null, location text, quantity integer not null default 0,
      isbn text, publisher_barcode text, publisher text, publisher_item_number text, author text,
      category text, subject text, curriculum text, grade_level text, edition text, final_price numeric,
      image_url text, item_type text not null default 'individual', bundle_piece_count integer not null default 0,
      status text default 'Available', public_visible boolean default true, notes text,
      label_printed boolean default true,
      square_item_id text, square_variation_id text, square_expected_quantity integer,
      square_inventory_synced_at timestamptz, created_at timestamptz not null default now(), updated_at timestamptz default now()
    );
    create table public.profiles (id uuid primary key, is_active boolean, role text);
    create function public.current_profile_is_active() returns boolean language sql stable as $$ select true $$;
    create function public.current_profile_is_admin() returns boolean language sql stable as $$ select true $$;
    create table public.curriculum_materials (id uuid primary key default gen_random_uuid());
    create table public.curriculum_packages (id uuid primary key default gen_random_uuid());
    create table public.curriculum_package_items (id uuid primary key default gen_random_uuid(), package_id uuid, material_id uuid);
    create table public.curriculum_inventory_matches (id uuid primary key default gen_random_uuid(), material_id uuid, inventory_item_id text);
    create sequence public.inventory_sku_seq;
    create function public.next_inventory_sku(p_item_type text default 'individual') returns text language sql as $$ select 'ILHRC-TEST' $$;
    create table public.book_reservations (
      id uuid primary key default gen_random_uuid(), item_id text not null, customer_name text not null,
      email text not null default '', phone text not null default '', preferred_contact text not null default 'email',
      status text not null default 'pending', expires_at timestamptz not null default now() + interval '14 days',
      created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
      handled_by uuid, square_hold_synced_at timestamptz, square_hold_released_at timestamptz
    );
    create table public.bundle_components (id bigint generated by default as identity primary key, bundle_item_id text, component_item_id text, piece_quantity integer);
    create table public.audit_logs (id bigint generated by default as identity primary key, user_id uuid, action text, entity_type text, entity_id text, details jsonb);
    create table public.square_inventory_events (
      event_id text, square_variation_id text, location_id text, state text not null default 'IN_STOCK',
      quantity integer, calculated_at timestamptz, primary key(event_id, square_variation_id, location_id, state)
    );
  `);
  if (migrated) {
    await db.exec(await readFile(locationMigration, "utf8"));
    await db.exec(await readFile(modernizationMigration, "utf8"));
    await db.exec(await readFile(publicCatalogAccessMigration, "utf8"));
  }
  return db;
}

async function scalar(db, sql, params = []) {
  const result = await db.query(sql, params);
  return Object.values(result.rows[0])[0];
}

test("transition availability preserves legacy stock without treating it as verified", async () => {
  const db = await database();
  await db.exec(`
    insert into public.items (id, sku, title) values ('book','SKU-A','Availability Book');
    insert into public.inventory_locations (code, display_name, location_type, last_verified_at)
    values ('A1','A1','shelf',now()), ('B2','B2','shelf',now());
    insert into public.inventory_by_location (item_id, location_id, quantity)
    select 'book', id, case code when 'A1' then 2 when 'B2' then 3 when 'HOLD' then 7
      when 'PROCESSING' then 6 when 'UNVERIFIED_LEGACY' then 5 else 0 end
    from public.inventory_locations where code in ('A1','B2','HOLD','PROCESSING','UNVERIFIED_LEGACY');
  `);
  const availability = (await db.query("select * from public.inventory_item_availability where item_id='book'")).rows[0];
  assert.equal(Number(availability.total_physical_quantity), 23);
  assert.equal(Number(availability.sellable_quantity), 5);
  assert.equal(Number(availability.catalog_sellable_quantity), 10);
  assert.equal(Number(availability.strict_available_to_reserve), 5);
  assert.equal(Number(availability.available_to_reserve), 10);
  assert.equal(availability.catalog_availability_mode, "legacy_compatible");
  await db.close();
});

test("catalog cutover is guarded until unverified inventory is resolved", async () => {
  const db = await database();
  await db.exec(`
    insert into public.items (id, sku, title, quantity)
    values ('legacy-book','SKU-LEGACY','Legacy Book',2);
  `);

  assert.equal(Number(await scalar(db, "select quantity from public.public_catalog_items where id='legacy-book'")), 2);
  await assert.rejects(
    db.query("select * from public.set_inventory_catalog_availability_mode('location_verified')"),
    /Cutover blocked: 2 unverified copies across 1 titles/
  );
  assert.equal(await scalar(db, "select catalog_availability_mode from public.inventory_rollout_settings"), "legacy_compatible");

  await db.query("select * from public.set_inventory_catalog_availability_mode('location_verified', true)");
  assert.equal(Number(await scalar(db, "select count(*) from public.public_catalog_items where id='legacy-book'")), 0);
  await assert.rejects(
    db.query("select * from public.allocate_sellable_inventory('legacy-book',1,'sale')"),
    /Insufficient sellable inventory/
  );

  await db.query("select * from public.set_inventory_catalog_availability_mode('legacy_compatible')");
  const allocation = await db.query("select * from public.allocate_sellable_inventory('legacy-book',1,'sale')");
  assert.equal(allocation.rows[0].location_code, "UNVERIFIED_LEGACY");
  assert.equal(Number(await scalar(db, "select quantity from public.items where id='legacy-book'")), 1);
  await db.close();
});

